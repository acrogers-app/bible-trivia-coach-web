// Writes src/lib/bibleStructure.ts: how many verses each chapter of each book has in the
// World English Bible (db/web.sqlite), so pickers only offer chapters and verses that exist.
//   node scripts/buildBibleStructure.mjs
import fs from "node:fs";
import Database from "better-sqlite3";

const db = new Database("db/web.sqlite", { readonly: true });
const rows = db.prepare("select book_id b, chapter c, max(number) v from verses group by b, c order by b, c").all();
const books = [];
for (const r of rows) (books[r.b - 1] ??= [])[r.c - 1] = r.v;
if (books.length !== 66 || books.some((ch) => !ch || ch.includes(undefined))) throw new Error("Unexpected WEB structure");
fs.writeFileSync("src/lib/bibleStructure.ts",
`// Generated by scripts/buildBibleStructure.mjs from db/web.sqlite. Do not edit by hand.
// VERSE_COUNTS[bookIndex][chapter - 1] = number of verses, books in canonical order (66).
export const VERSE_COUNTS: readonly (readonly number[])[] = ${JSON.stringify(books)};

/** Chapters in a book (bookIndex 0–65), or 0 if unknown. */
export function chapterCount(bookIndex: number): number {
  return VERSE_COUNTS[bookIndex]?.length ?? 0;
}

/** Verses in a chapter (1-based), or 0 if unknown. */
export function verseCount(bookIndex: number, chapter: number): number {
  return VERSE_COUNTS[bookIndex]?.[chapter - 1] ?? 0;
}
`);
console.log(`66 books, ${rows.length} chapters`);
